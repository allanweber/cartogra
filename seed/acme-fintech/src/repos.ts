import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import type { SeedData, SeedService } from './schema.ts'

export interface RepoOptions {
  githubOrg?: string
  azureOrg?: string
  azureProject?: string
}

export type RepoFiles = Map<string, string>

const STACK_LABEL = { java: 'Java 21 / Spring Boot', node: 'Node.js 22 / Express', python: 'Python 3.12 / FastAPI' } as const

interface Route {
  method: 'GET' | 'POST'
  path: string
  summary: string
}

export function routesFor(service: SeedService): Route[] {
  const base = service.name.replace(/-service$/, '')
  const resource = base.endsWith('s') ? base : `${base}s`
  return [
    { method: 'GET', path: `/${resource}`, summary: `List ${resource}` },
    { method: 'POST', path: `/${resource}`, summary: `Create ${resource.replace(/s$/, '')}` },
    { method: 'GET', path: `/${resource}/{id}`, summary: `Get ${resource.replace(/s$/, '')} by ID` },
  ]
}

export function teamSlug(team: string): string {
  return team.toLowerCase().replace(/[^a-z0-9]+/g, '-')
}

/** Pure: everything a repo contains, so provider scanning (tech stack, OpenAPI, CODEOWNERS) has real inputs. */
export function renderRepo(service: SeedService, options: RepoOptions = {}): RepoFiles {
  const files: RepoFiles = new Map()
  const { stack, port, provider } = service.repo
  files.set('README.md', readme(service))
  files.set('openapi.yaml', openapi(service))
  files.set('.dockerignore', '.git\nbuild/\n.gradle/\ntarget/\n*.md\n.env\nnode_modules/\n__pycache__/\n*.pyc\ndist/\n')
  if (service.team !== null) {
    const slug = teamSlug(service.team)
    const owner = provider === 'github' && options.githubOrg ? `@${options.githubOrg}/${slug}` : `@${slug}`
    files.set('CODEOWNERS', `* ${owner}\n`)
  }
  for (const [path, content] of stackFiles(service, stack, port)) files.set(path, content)
  return files
}

function readme(s: SeedService): string {
  return `# ${s.name}

${s.description}

## Metadata
| Field | Value |
|-------|-------|
| Team  | ${s.team ?? 'unowned'} |
| Tier  | ${s.tier} |
| Stack | ${STACK_LABEL[s.repo.stack]} |
| Port  | ${s.repo.port} |

Part of the Acme Fintech seed (generated by \`pnpm acme repos\`). Do not edit by hand.
`
}

function openapi(s: SeedService): string {
  const routes = routesFor(s)
  const paths = [...new Set(routes.map((r) => r.path))]
  const body = paths
    .map((path) => {
      const ops = routes
        .filter((r) => r.path === path)
        .map((r) => `    ${r.method.toLowerCase()}:\n      summary: "${r.summary}"\n      responses:\n        "200":\n          description: OK\n`)
        .join('')
      return `  "${path}":\n${ops}`
    })
    .join('')
  return `openapi: "3.0.3"\ninfo:\n  title: "${s.name}"\n  version: "1.0.0"\nservers:\n  - url: "http://localhost:${s.repo.port}"\npaths:\n${body}`
}

function stackFiles(s: SeedService, stack: SeedService['repo']['stack'], port: number): RepoFiles {
  const files: RepoFiles = new Map()
  const routes = routesFor(s)
  if (stack === 'java') {
    files.set('settings.gradle.kts', `rootProject.name = "${s.name}"\n`)
    files.set(
      'build.gradle.kts',
      `plugins {\n    java\n    id("org.springframework.boot") version "3.4.0"\n    id("io.spring.dependency-management") version "1.1.6"\n}\n\ngroup = "io.acmefintech"\nversion = "1.0.0"\n\njava {\n    toolchain { languageVersion = JavaLanguageVersion.of(21) }\n}\n\nrepositories { mavenCentral() }\n\ndependencies {\n    implementation("org.springframework.boot:spring-boot-starter-web")\n    implementation("org.springframework.boot:spring-boot-starter-actuator")\n}\n`,
    )
    files.set(
      'src/main/resources/application.yml',
      `server:\n  port: ${port}\nmanagement:\n  endpoint:\n    health:\n      probes:\n        enabled: true\n`,
    )
    const methods = routes
      .map((r, i) => `    @${r.method === 'GET' ? 'Get' : 'Post'}Mapping("${r.path}")\n    public Map<String, String> route${i}() { return Map.of("status", "ok"); }\n`)
      .join('\n')
    files.set(
      'src/main/java/io/acmefintech/App.java',
      `package io.acmefintech;\n\nimport java.util.Map;\nimport org.springframework.boot.SpringApplication;\nimport org.springframework.boot.autoconfigure.SpringBootApplication;\nimport org.springframework.web.bind.annotation.*;\n\n@SpringBootApplication\n@RestController\npublic class App {\n    public static void main(String[] args) { SpringApplication.run(App.class, args); }\n\n${methods}}\n`,
    )
    files.set(
      'Dockerfile',
      `FROM eclipse-temurin:21-jdk-jammy AS builder\nWORKDIR /build\nCOPY . .\nRUN ./gradlew bootJar --no-daemon -q\n\nFROM eclipse-temurin:21-jre-jammy\nRUN useradd -m -u 1000 appuser\nWORKDIR /app\nCOPY --from=builder /build/build/libs/*.jar app.jar\nUSER appuser\nEXPOSE ${port}\nENTRYPOINT ["sh", "-c", "exec java \${JAVA_OPTS:-} -jar app.jar"]\n`,
    )
  } else if (stack === 'node') {
    files.set('package.json', `{\n  "name": "${s.name}",\n  "version": "1.0.0",\n  "private": true,\n  "scripts": { "start": "node src/index.js" },\n  "dependencies": { "express": "^4.21.0" }\n}\n`)
    const lines = routes.map((r) => `app.${r.method.toLowerCase()}('${r.path.replace('{id}', ':id')}', (_, res) => res.json({ status: 'ok' }))`).join('\n')
    files.set(
      'src/index.js',
      `'use strict'\nconst express = require('express')\nconst app = express()\napp.use(express.json())\napp.get('/actuator/health', (_, res) => res.json({ status: 'UP' }))\n${lines}\napp.listen(process.env.PORT || ${port})\n`,
    )
    files.set(
      'Dockerfile',
      `FROM node:22-slim AS builder\nWORKDIR /build\nCOPY package*.json ./\nRUN npm install\n\nFROM node:22-slim\nWORKDIR /app\nCOPY --from=builder /build/node_modules ./node_modules\nCOPY src ./src\nCOPY package.json ./\nUSER node\nEXPOSE ${port}\nENTRYPOINT ["node", "src/index.js"]\n`,
    )
  } else {
    files.set('requirements.txt', 'fastapi==0.115.0\nuvicorn[standard]==0.32.0\n')
    const defs = routes.map((r, i) => `@app.${r.method.toLowerCase()}("${r.path}")\ndef route_${i}(): return {"status": "ok"}\n`).join('\n')
    files.set('main.py', `from fastapi import FastAPI\n\napp = FastAPI(title="${s.name}", version="1.0.0")\n\n@app.get("/actuator/health")\ndef health(): return {"status": "UP"}\n\n${defs}`)
    files.set(
      'Dockerfile',
      `FROM python:3.12-slim AS builder\nWORKDIR /build\nCOPY requirements.txt .\nRUN pip install --no-cache-dir --prefix=/install -r requirements.txt\n\nFROM python:3.12-slim\nRUN useradd -m -u 1000 appuser\nWORKDIR /app\nCOPY --from=builder /install /usr/local\nCOPY main.py ./\nUSER appuser\nEXPOSE ${port}\nENTRYPOINT ["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "${port}"]\n`,
    )
  }
  return files
}

export interface RemoteTarget {
  url: string
  create: () => void
}

export function remoteFor(service: SeedService, options: RepoOptions): RemoteTarget {
  if (service.repo.provider === 'github') {
    const org = required(options.githubOrg, 'ACME_GITHUB_ORG')
    return {
      url: `https://github.com/${org}/${service.name}.git`,
      create: () => createRepo('gh', ['repo', 'create', `${org}/${service.name}`, '--public', '--description', service.description]),
    }
  }
  const org = required(options.azureOrg, 'ACME_AZURE_ORG').replace(/\/$/, '')
  const project = required(options.azureProject, 'ACME_AZURE_PROJECT')
  return {
    url: `${org}/${project}/_git/${service.name}`,
    create: () => createRepo('az', ['repos', 'create', '--name', service.name, '--project', project, '--org', org, '--output', 'none']),
  }
}

export interface PushSummary {
  pushed: string[]
  unchanged: string[]
}

/** Idempotent: clones, rewrites generated files, commits only when something changed. */
export function pushRepos(seed: SeedData, options: RepoOptions, log: (m: string) => void = () => {}): PushSummary {
  const summary: PushSummary = { pushed: [], unchanged: [] }
  const work = mkdtempSync(join(tmpdir(), 'acme-repos-'))
  const azureAuth = seed.services.some((s) => s.repo.provider === 'azure') ? azureGitAuth() : []
  try {
    for (const service of seed.services) {
      const remote = remoteFor(service, options)
      remote.create()
      const dir = join(work, service.name)
      const auth = service.repo.provider === 'azure' ? azureAuth : []
      run('git', [...auth, 'clone', '--quiet', remote.url, dir], false)
      run('git', ['-C', dir, 'checkout', '-B', 'main'], false)
      for (const entry of readdirSync(dir)) if (entry !== '.git') rmSync(join(dir, entry), { recursive: true, force: true })
      for (const [path, content] of renderRepo(service, options)) {
        mkdirSync(dirname(join(dir, path)), { recursive: true })
        writeFileSync(join(dir, path), content)
      }
      run('git', ['-C', dir, 'add', '-A'], false)
      if (changed(dir)) {
        run('git', ['-C', dir, '-c', 'user.name=Acme Seed', '-c', 'user.email=acme-seed@example.invalid', 'commit', '--quiet', '-m', 'chore: sync acme seed scaffold'], false)
        run('git', [...auth, '-C', dir, 'push', '--quiet', '-u', 'origin', 'main'], false)
        summary.pushed.push(service.name)
        log(`pushed ${service.name} (${service.repo.provider})`)
      } else {
        summary.unchanged.push(service.name)
        log(`unchanged ${service.name}`)
      }
    }
  } finally {
    rmSync(work, { recursive: true, force: true })
  }
  return summary
}

const AZURE_DEVOPS_RESOURCE = '499b84ac-1321-427f-aa17-267ca6975798'

/** PAT (ACME_AZURE_PAT) when set; otherwise the `az login` token, which only some orgs (Entra-backed) accept. */
function azureGitAuth(): string[] {
  const pat = process.env.ACME_AZURE_PAT
  if (pat) return ['-c', `http.extraHeader=Authorization: Basic ${Buffer.from(`:${pat}`).toString('base64')}`]
  const token = execFileSync('az', ['account', 'get-access-token', '--resource', AZURE_DEVOPS_RESOURCE, '--query', 'accessToken', '-o', 'tsv'], {
    encoding: 'utf8',
  }).trim()
  return ['-c', `http.extraHeader=Authorization: Bearer ${token}`]
}

function changed(dir: string): boolean {
  return execFileSync('git', ['-C', dir, 'status', '--porcelain'], { encoding: 'utf8' }).trim().length > 0
}

/** Tolerates only "already exists"; anything else (missing CLI, no auth, unknown project) aborts with the CLI's message. */
function createRepo(command: string, args: string[]): void {
  try {
    execFileSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'ignore', 'pipe'] })
  } catch (error) {
    const e = error as NodeJS.ErrnoException & { stderr?: string }
    if (e.code === 'ENOENT') throw new Error(`\`${command}\` is not installed or not on PATH`)
    const message = e.stderr ?? String(error)
    if (/already exists|TF400948/i.test(message)) return
    throw new Error(`${command} repo create failed: ${message.trim()}`)
  }
}

function run(command: string, args: string[], tolerateFailure: boolean): void {
  try {
    execFileSync(command, args, {
      stdio: ['ignore', 'ignore', tolerateFailure ? 'ignore' : 'inherit'],
      env: { ...process.env, GIT_TERMINAL_PROMPT: '0' },
    })
  } catch (error) {
    if (!tolerateFailure) throw error
  }
}

function required(value: string | undefined, name: string): string {
  if (!value) throw new Error(`${name} is required`)
  return value
}
